from typing import Protocol, runtime_checkable


@runtime_checkable
class Workspace(Protocol):
    def read_file(self, path: str) -> str: ...
    def list_files(self) -> list[str]: ...
    def write_file(self, path: str, content: str) -> None: ...
    def commit(self, branch: str, message: str) -> None:
        """Commit all changes on this branch. Make the branch from the current commit if it does not exist."""
        ...

    def discard_changes(self) -> None:
        """Throw away the changes that are not in a commit. The files go back to the last commit."""
        ...
